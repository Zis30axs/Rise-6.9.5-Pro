import {test,expect} from '@playwright/test';
for (const [width,height] of [[1440,900],[1280,800],[390,844],[320,568]]) {
  test(`Xitter public identity and profile ${width}x${height}`,async({page})=>{
    const errors:string[]=[];const requests:string[]=[];
    page.on('pageerror',e=>errors.push(e.message));
    page.on('request',r=>{if(/^https?:/.test(r.url()) && new URL(r.url()).hostname!=='127.0.0.1')requests.push(r.url());});
    await page.setViewportSize({width,height});
    await page.goto('/outputs/xitter-qa/index.html');
    await expect(page.locator('[data-action="network-profile"]').first()).toContainText('CucumberT_T');
    const app=page.locator('#app');
    await expect(app).not.toContainText(/若叶睦|@post\.sov|LLM|调用模型|person:|world_actions/);
    expect(await page.evaluate(()=> (window as any).xitterQA.count())).toBe(0);
    for(const img of await app.locator('img').all())expect(await img.evaluate((e:HTMLImageElement)=>e.complete&&e.naturalWidth>0)).toBe(true);
    await page.screenshot({path:`outputs/xitter-qa/${width}-feed.png`});
    await app.locator('[data-action="network-profile"]').first().click();
    await expect(app).toContainText('mutsumi@post.sov');
    await app.getByRole('button',{name:'关注',exact:true}).click();
    await expect(app.getByRole('button',{name:'已关注',exact:true})).toBeVisible();
    await page.screenshot({path:`outputs/xitter-qa/${width}-profile.png`});
    await page.reload();
    await app.locator('[data-action="network-profile"]').first().click();
    await expect(app.getByRole('button',{name:'已关注',exact:true})).toBeVisible();
    await page.getByRole('button',{name:'返回',exact:true}).click();
    await app.locator('[data-action="open-post"]').first().click();
    await expect(app).toContainText('@tomori');
    await expect(app).not.toContainText('@post.sov');
    await app.getByRole('button',{name:'点赞',exact:true}).click();
    await expect(app.getByRole('button',{name:'取消点赞',exact:true})).toBeVisible();
    await app.getByRole('button',{name:'取消点赞',exact:true}).click();
    await expect(app.getByRole('button',{name:'点赞',exact:true})).toBeVisible();
    await page.getByRole('button',{name:'返回',exact:true}).click();
    await app.getByRole('button',{name:'发现账号'}).click();
    await app.locator('[data-account="band:crychic"]').click();
    await expect(app).toContainText('休眠中');
    await expect(app.locator('.forum-card')).toHaveCount(0);
    await app.getByRole('button',{name:'关注',exact:true}).click();
    await expect(app.getByRole('button',{name:'已关注',exact:true})).toBeVisible();
    await page.screenshot({path:`outputs/xitter-qa/${width}-crychic.png`});
    await page.evaluate(()=> (window as any).xitterQA.switchOwner('sakiko'));
    await expect(app).toContainText('@mutsumi');
    await app.getByRole('button',{name:'刷新 Xitter',exact:true}).click();
    await expect(app).toContainText('路过的纸飞机');
    expect(await page.evaluate(()=> (window as any).xitterQA.count())).toBe(1);
    await expect(app).not.toContainText('@post.sov');
    expect(await page.evaluate(()=>Array.from(document.querySelectorAll('#app button')).every(b=>!b.querySelector('button')))).toBe(true);
    expect(await app.evaluate(e=>e.scrollWidth<=e.clientWidth)).toBe(true);
    expect(await app.locator('.view').evaluate(e=>e.scrollWidth<=e.clientWidth)).toBe(true);
    expect(errors).toEqual([]);expect(requests).toEqual([]);
  });
}
