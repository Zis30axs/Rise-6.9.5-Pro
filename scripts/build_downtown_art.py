#!/usr/bin/env python3
"""Build one trusted inline art module. Pending artwork never becomes a release."""
from __future__ import annotations
import argparse
import base64
import hashlib
import json
import os
from pathlib import Path
import tempfile
from verify_downtown_art import validate_assets

BASE = Path(__file__).resolve().parents[1]


def build_pack(root: Path, manifest: Path, output: Path, require_ready: bool = False) -> dict:
    source = json.loads(manifest.read_text(encoding='utf-8'))
    if not isinstance(source, dict) or source.get('schemaVersion') != 1:
        raise ValueError('Unsupported downtown art manifest')
    ready = source.get('reviewStatus') == 'approved'
    if require_ready and not ready:
        raise ValueError('Final artwork has not been reviewed; release blocked')
    pack = {'ready': False, 'reason': 'Runtime artwork is pending review and installation.', 'assets': {}}
    total = 0
    if ready:
        report = validate_assets(root, manifest)
        assets = {}
        original = {entry['id']: entry for entry in source['assets']}
        for entry in report['assets']:
            path = (root / entry['path']).resolve()
            data = path.read_bytes()
            if hashlib.sha256(data).hexdigest() != entry['sha256']:
                raise ValueError('Asset changed after validation: ' + entry['id'])
            mime = 'webp' if path.suffix.lower() == '.webp' else 'png'
            asset = {'id': entry['id'], 'src': 'data:image/' + mime + ';base64,' + base64.b64encode(data).decode('ascii'),
                     'width': entry['size'][0], 'height': entry['size'][1], 'sha256': entry['sha256']}
            if 'anchor' in original[entry['id']]:
                asset['anchor'] = original[entry['id']]['anchor']
            assets[entry['id']] = asset
            total += len(data)
        pack = {'ready': True, 'assets': assets}
    text = ("// Generated by scripts/build_downtown_art.py. No private state or external URLs.\n"
            "import type { DowntownArtPack } from '../downtown-art-runtime';\n"
            "export const downtownArtPack: DowntownArtPack = Object.freeze("
            + json.dumps(pack, ensure_ascii=True, separators=(',', ':')) + ");\n")
    # Validation completes before replacing the last usable generated module.
    output.parent.mkdir(parents=True, exist_ok=True)
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(mode='w', encoding='utf-8', dir=output.parent, delete=False) as stream:
            temporary = Path(stream.name)
            stream.write(text)
        os.replace(temporary, output)
    finally:
        if temporary is not None and temporary.exists():
            temporary.unlink()
    return {'ready': ready, 'assetCount': len(pack['assets']), 'assetBytes': total,
            'moduleBytes': len(text.encode('utf-8')), 'moduleSha256': hashlib.sha256(text.encode('utf-8')).hexdigest()}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=BASE / 'assets/downtown-art')
    parser.add_argument('--manifest', type=Path, default=BASE / 'integration/downtown-art/manifest.json')
    parser.add_argument('--output', type=Path, default=BASE / 'src/frontend/generated/downtown-art.ts')
    parser.add_argument('--require-ready', action='store_true')
    args = parser.parse_args()
    try:
        result = build_pack(args.root, args.manifest, args.output, args.require_ready)
        print(json.dumps(result, indent=2))
        if not result['ready']:
            print('PREVIEW ONLY: existing scene backgrounds are retained; new illustrations are NOT installed.')
        return 0
    except (ValueError, OSError, TypeError, KeyError) as error:
        print('ART BUILD BLOCKED: ' + str(error))
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
