#!/usr/bin/env python3
"""Fail the standard local build if its canonical offline California GLB is unavailable.

The file is generated by scripts/build_california_sandbox_glb.py and committed
as a versioned project source, never fetched from a CDN or CI artifact. This
check only verifies the committed file; re-running the generator reproduces it.
"""
from __future__ import annotations

import hashlib
import json
import re
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODEL_RELATIVE = Path("assets/models/unread-city-california-sandbox.glb")
BRIDGE_RELATIVE = Path("src/frontend/california-sandbox-map.ts")
MAX_MODEL_BYTES = 10_000_000


def read_model(source: Path) -> bytes:
    data = source.read_bytes()
    if len(data) < 20 or len(data) > MAX_MODEL_BYTES or data[:4] != b"glTF":
        raise ValueError("不是有效的加州沙盘 GLB。")
    version, total, length, tag = struct.unpack_from("<IIII", data, 4)
    if version != 2 or total != len(data) or tag != 0x4E4F534A or length > len(data) - 20:
        raise ValueError("GLB 头或 JSON 数据块无效。")
    metadata = json.loads(data[20:20 + length])
    for kind in ("buffers", "images"):
        if any("uri" in entry for entry in metadata.get(kind, [])):
            raise ValueError("沙盘模型不允许携带外部纹理或 buffer 地址。")
    return data


def main() -> int:
    model = ROOT / MODEL_RELATIVE
    if not model.is_file():
        print(
            f"加州沙盘源模型未入库：{MODEL_RELATIVE}。"
            "请先运行 scripts/build_california_sandbox_glb.py 生成并提交；"
            "正常 Lite 构建不得依赖临时文件路径或网络下载。",
            file=sys.stderr,
        )
        return 1
    bridge = (ROOT / BRIDGE_RELATIVE).read_text(encoding="utf-8")
    match = re.search(r"CALIFORNIA_SANDBOX_MODEL_SHA256 =\n?\s*'([0-9a-f]{64})'", bridge)
    if not match:
        print("加州沙盘桥接文件未登记模型 SHA-256。", file=sys.stderr)
        return 1
    try:
        data = read_model(model)
    except (OSError, ValueError, KeyError) as exc:
        print(f"加州沙盘 GLB 校验失败：{exc}", file=sys.stderr)
        return 1
    sha = hashlib.sha256(data).hexdigest()
    if sha != match.group(1):
        print(
            f"加州沙盘 GLB 与桥接登记不一致：文件 {sha}，登记 {match.group(1)}。"
            "请重新运行 scripts/build_california_sandbox_glb.py 并同步登记。",
            file=sys.stderr,
        )
        return 1
    print(f"加州沙盘源模型已校验：{MODEL_RELATIVE} ({len(data):,} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
