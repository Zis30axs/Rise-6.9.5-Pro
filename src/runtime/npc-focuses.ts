interface FocusStepSpec {
  id: string;
  title: string;
  description: string;
  durationMinutes: number;
  aiWeight: number;
  statAmount: number;
  balanceDelta?: number;
  available?: Condition;
  bypass?: Condition;
  cancel?: Condition;
  aiModifiers?: FocusAiModifier[];
}

function buildFocus(
  owner: string,
  stat: NpcCircleStat,
  spec: FocusStepSpec,
  prerequisites?: Condition,
  branchGroup?: string,
): FocusDefinition {
  const onComplete: StrategyEffect[] = [{ type: 'add_stat', key: stat, amount: spec.statAmount }];
  if (typeof spec.balanceDelta === 'number' && spec.balanceDelta !== 0) {
    onComplete.push({ type: 'shift_balance', delta: spec.balanceDelta });
  }
  return {
    id: spec.id,
    owner,
    title: spec.title,
    description: spec.description,
    durationMinutes: spec.durationMinutes,
    aiWeight: spec.aiWeight,
    ...(prerequisites ? { prerequisites } : {}),
    ...(branchGroup ? { branchGroup } : {}),
    ...(spec.available ? { available: spec.available } : {}),
    ...(spec.bypass ? { bypass: spec.bypass } : {}),
    ...(spec.cancel ? { cancel: spec.cancel } : {}),
    ...(spec.aiModifiers?.length ? { aiModifiers: spec.aiModifiers } : {}),
    onComplete,
  };
}

/** Root focus leading into two mutually exclusive personal directions. */
function branchTree(
  owner: string,
  stat: NpcCircleStat,
  branchGroup: string,
  root: FocusStepSpec,
  left: FocusStepSpec,
  right: FocusStepSpec,
): FocusDefinition[] {
  const afterRoot: Condition = { completed: root.id };
  return [
    buildFocus(owner, stat, root),
    buildFocus(owner, stat, left, afterRoot, branchGroup),
    buildFocus(owner, stat, right, afterRoot, branchGroup),
  ];
}

/** Sequential three-step personal routine or growth track. */
function chainTree(
  owner: string,
  stat: NpcCircleStat,
  first: FocusStepSpec,
  second: FocusStepSpec,
  third: FocusStepSpec,
): FocusDefinition[] {
  return [
    buildFocus(owner, stat, first),
    buildFocus(owner, stat, second, { completed: first.id }),
    buildFocus(owner, stat, third, { completed: second.id }),
  ];
}

