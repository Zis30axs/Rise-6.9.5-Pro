type Clock = WorldState['clock'];
type OpeningPeriod = 'morning' | 'day' | 'evening' | 'night';

// Use the shared game clock, including the hours after midnight.
function openingPeriod(clock: Clock): OpeningPeriod {
  if (clock.hour < 5 || clock.hour >= 19) return 'night';
  if (clock.hour < 9) return 'morning';
  if (clock.hour < 17) return 'day';
  return 'evening';
}

